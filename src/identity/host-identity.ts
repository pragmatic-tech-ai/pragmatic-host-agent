import { chmod } from 'node:fs/promises'
import { SigningKeyPair } from '@pragmatic-tech-ai/pragmatic-hive-protocol'
import { StateFiles } from '../state/state-files.js'

/** The key file exists but holds no usable Ed25519 key (edited by hand?): never silently replaced. */
export class HostIdentityUnusableError extends Error
{
    private static readonly ErrorName = 'HostIdentityUnusableError'
    private static readonly Text = 'the host key file host-key.pem in the state directory holds no usable Ed25519 key; remove it to enrol the machine again with a new key'

    public constructor()
    {
        super(HostIdentityUnusableError.Text)
        this.name = HostIdentityUnusableError.ErrorName
    }
}

/**
 * The machine's own Ed25519 key (C5.1): generated by the host agent the first time it starts and kept as PKCS#8 PEM in
 * `<state dir>/host-key.pem`, mode 0600, never replaced, so a restart (even one mid-enrolment) signs with the same key.
 * The private half never leaves the file and appears in no log line or message; the platform records only the public
 * half.
 */
export class HostIdentity
{
    public static readonly KeyFile = 'host-key.pem'

    private constructor()
    {
    }

    public static async LoadOrCreate(files: StateFiles): Promise<SigningKeyPair>
    {
        const H = HostIdentity
        const path = files.Path(H.KeyFile)
        const existing = await H.Load(files, path)
        if (existing !== undefined)
        {
            return existing
        }
        const key = SigningKeyPair.Generate()
        if (await files.CreateExclusive(path, key.PrivatePem()))
        {
            return key
        }
        // Another start created it first: use that one.
        const raced = await H.Load(files, path)
        if (raced === undefined)
        {
            throw new HostIdentityUnusableError()
        }
        return raced
    }

    private static async Load(files: StateFiles, path: string): Promise<SigningKeyPair | undefined>
    {
        const pem = await files.ReadText(path)
        if (pem === undefined)
        {
            return undefined
        }
        let key: SigningKeyPair
        try
        {
            key = SigningKeyPair.FromPrivatePem(pem)
        }
        catch
        {
            throw new HostIdentityUnusableError()
        }
        // Whatever mode the file was left in, it is the owner's only.
        await chmod(path, StateFiles.FileMode)
        return key
    }
}
